const wssHostEmptyRuleset = `{"nftables":[{"metainfo":{"version":"1.1.3","json_schema_version":1}}]}`

const wssHostLegacyEmpty = `# Generated by iptables-save v1.8.11
*filter
:INPUT ACCEPT [0:0]
:FORWARD ACCEPT [0:0]
:OUTPUT ACCEPT [0:0]
COMMIT
# Completed
`

func wssHostEvidence(raw string) WSSWGFirewallEvidence {
	return WSSWGFirewallEvidence{
		NFTRuleset:   []byte(raw),
		IPTablesV4:   "iptables v1.8.11 (nf_tables)",
		IPTablesV6:   "ip6tables v1.8.11 (nf_tables)",
		LegacySaveV4: []byte(wssHostLegacyEmpty),
		LegacySaveV6: []byte{},
	}
}

func wssHostInventory(t *testing.T, table, chain, hook string, priority int, policy string, rule bool) string {
	t.Helper()
	objects := []any{
		map[string]any{"metainfo": map[string]any{"version": "1.1.3", "json_schema_version": 1}},
		map[string]any{"table": map[string]any{"family": "inet", "name": table}},
	}
	c := map[string]any{"family": "inet", "table": table, "name": chain}
	if hook != "" {
		c["hook"], c["prio"], c["policy"], c["type"] = hook, priority, policy, "filter"
	}
	objects = append(objects, map[string]any{"chain": c})
	if rule {
		objects = append(objects, map[string]any{"rule": map[string]any{
			"family": "inet", "table": table, "chain": chain,
			"expr": []any{map[string]any{"accept": nil}},
		}})
	}
	data, err := json.Marshal(map[string]any{"nftables": objects})
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

func TestWSSWGHostCoexistenceAcceptsOnlyBoundedReadOnlyEvidence(t *testing.T) {
	p := wssGuardFixture(t)
	for _, input := range []string{
		wssHostEmptyRuleset,
		wssHostInventory(t, "filter", "INPUT", "input", 0, "accept", true),
		wssHostInventory(t, "raw", "PREROUTING", "prerouting", -300, "accept", false),
		wssHostInventory(t, "misc", "inactive", "", 0, "", true),
	} {
		if err := p.CheckWSSWGFirewallCoexistence(wssHostEvidence(input)); err != nil {
			t.Fatalf("allowed independent later/empty host policy rejected: %v", err)
		}
	}
	// A per-Link guard must never be considered owned because it has the
	// expected public table name and marker; even a pristine clone collides.
	if err := p.CheckWSSWGNFTCoexistence([]byte(wssHostInventory(t, p.tableName(), "ingress", "input", -250, "accept", true))); err == nil {
		t.Fatal("adopted same-name existing nft guard")
	}
}

func TestWSSWGHostCoexistenceRejectsDuplicateOrIncompleteNFTJSON(t *testing.T) {
	p := wssGuardFixture(t)
	valid := wssHostInventory(t, "foreign", "INPUT", "input", 0, "accept", true)
	if err := p.CheckWSSWGNFTCoexistence([]byte(valid)); err != nil {
		t.Fatalf("canonical non-empty nft inventory was rejected: %v", err)
	}
	if err := p.CheckWSSWGNFTCoexistence([]byte(wssHostEmptyRuleset)); err != nil {
		t.Fatalf("canonical empty nft inventory was rejected: %v", err)
	}
	// Restrict the *keys*, not legitimate non-ASCII names or other values.
	withUnicodeValues := `{"nftables":[{"metainfo":{"version":"1.1.3","release_name":"نسخه","json_schema_version":1}},{"table":{"family":"inet","name":"شبکه"}}]}`
	if err := p.CheckWSSWGNFTCoexistence([]byte(withUnicodeValues)); err != nil {
		t.Fatalf("valid UTF-8 nft values were rejected: %v", err)
	}
	meta := `{"metainfo":{"version":"1.1.3","json_schema_version":1}}`
	for _, tt := range []struct {
		name string
		raw  string
	}{
		{"duplicate-top-level-nftables", `{"nftables":[{"table":{"family":"inet","name":"foreign"}}],"nftables":[` + meta + `]} `},
		{"duplicate-entry-object-name", `{"nftables":[{"table":{"family":"inet","name":"foreign"},"table":{"family":"inet","name":"safe"}},` + meta + `]} `},
		{"case-alias-top-level", `{"nftables":[` + meta + `],"NFTABLES":[` + meta + `]}`},
		{"unicode-alias-top-level", `{"nftables":[{"table":{"family":"inet","name":"foreign"}}],"nftable\u017f":[` + meta + `]}`},
		{"unicode-alias-alone", `{"nftable\u017f":[` + meta + `]}`},
		{"unicode-alias-entry", `{"nftables":[{"meta\u0131nfo":{"version":"1.1.3","json_schema_version":1}}]}`},
		{"duplicate-metadata-object-name", `{"nftables":[{"metainfo":{},"metainfo":{"version":"1.1.3","json_schema_version":1}}]}`},
		{"duplicate-metadata-version", strings.Replace(wssHostEmptyRuleset, `"version":"1.1.3"`, `"version":"unknown","version":"1.1.3"`, 1)},
		{"unicode-alias-metadata-version", strings.Replace(wssHostEmptyRuleset, `"version":"1.1.3"`, `"version":"hidden","ver\u017fion":"1.1.3"`, 1)},
		{"duplicate-schema-key", strings.Replace(wssHostEmptyRuleset, `"json_schema_version":1`, `"json_schema_version":2,"json_schema_version":1`, 1)},
		{"duplicate-chain-hook", strings.Replace(valid, `"hook":"input"`, `"hook":"prerouting","hook":"input"`, 1)},
		{"case-alias-chain-hook", strings.Replace(valid, `"hook":"input"`, `"Hook":"prerouting","hook":"input"`, 1)},
		{"unicode-alias-chain-policy", strings.Replace(valid, `"policy":"accept"`, `"policy":"drop","pol\u0131cy":"accept"`, 1)},
		{"unicode-key-nested-expression", strings.Replace(valid, `"accept":null`, `"accept":null,"مبهم":null`, 1)},
		{"duplicate-chain-priority", strings.Replace(valid, `"prio":0`, `"prio":-300,"prio":0`, 1)},
		{"duplicate-rule-member", strings.Replace(valid, `"accept":null`, `"accept":null,"accept":null`, 1)},
		{"empty-nftables-array", `{"nftables":[]}`},
		{"null-metainfo", `{"nftables":[{"metainfo":null}]}`},
		{"empty-metainfo", `{"nftables":[{"metainfo":{}}]}`},
		{"metainfo-no-version", `{"nftables":[{"metainfo":{"json_schema_version":1}}]}`},
		{"metainfo-null-version", `{"nftables":[{"metainfo":{"version":null,"json_schema_version":1}}]}`},
		{"metainfo-no-schema-version", `{"nftables":[{"metainfo":{"version":"1.1.3"}}]}`},
		{"metainfo-unknown-schema", `{"nftables":[{"metainfo":{"version":"1.1.3","json_schema_version":2}}]}`},
		{"duplicated-metainfo-entry", `{"nftables":[` + meta + `,` + meta + `]}`},
	} {
		t.Run(tt.name, func(t *testing.T) {
			// A negative fixture must be syntactically well-formed to prove
			// semantic rejection instead of accidentally testing JSON syntax.
			if !json.Valid([]byte(tt.raw)) {
				t.Fatal("invalid negative test fixture")
			}
			if err := p.CheckWSSWGNFTCoexistence([]byte(tt.raw)); err == nil {
				t.Fatal("malformed, duplicated or incomplete nft snapshot was admitted")
			}
		})
	}
}

func TestWSSWGHostCoexistenceRejectsForeignPreGuardPolicy(t *testing.T) {
	p := wssGuardFixture(t)
	for _, tt := range []struct {
		name     string
		table    string
		hook     string
		priority int
		policy   string
		rule     bool
	}{
		{"earlier-input-accept", "foreign", "input", -300, "accept", true},
		{"equal-priority-input", "foreign", "input", -250, "accept", true},
		{"earlier-input-drop", "foreign", "input", -300, "drop", false},
		{"prerouting-rule", "mangle", "prerouting", -100, "accept", true},
		{"ingress-rule", "device", "ingress", 0, "accept", true},
		{"prerouting-policy", "raw", "prerouting", -300, "drop", false},
	} {
		t.Run(tt.name, func(t *testing.T) {
			raw := wssHostInventory(t, tt.table, "foreign", tt.hook, tt.priority, tt.policy, tt.rule)
			if err := p.CheckWSSWGNFTCoexistence([]byte(raw)); err == nil {
				t.Fatal("failed open on effective or ambiguous foreign hook")
			}
		})
	}
	// Chain or rule state without a complete inventory cannot be trusted.
	for _, raw := range []string{
		"",
		"{}",
		`{"nftables":null}`,
		`{"nftables":[]}` + "{}",
		`{"nftables":[{"flowtable":{"family":"inet","name":"ft"}}]}`,
		`{"nftables":[{"chain":{"family":"inet","table":"filter","name":"INPUT","type":"filter","hook":"input","prio":-250,"policy":"accept"}}]}`,
		`{"nftables":[{"rule":{"family":"inet","table":"filter","chain":"INPUT","expr":[{"accept":null}]}}]}`,
		`{"nftables":[{"metainfo":{},"table":{}}]}`,
		wssHostInventory(t, "foreign", "INPUT", "input", -250, "accept", true) + "{}",
	} {
		if err := p.CheckWSSWGNFTCoexistence([]byte(raw)); err == nil {
			t.Fatalf("invalid or incomplete nft host policy accepted: %q", raw)
		}
	}
	huge := make([]byte, 8<<20+1)
	if err := p.CheckWSSWGNFTCoexistence(huge); err == nil {
		t.Fatal("unbounded nft readback accepted")
	}
}

func TestWSSWGHostCoexistenceRejectsUnverifiedMixedIPTables(t *testing.T) {
	p := wssGuardFixture(t)
	legible := wssHostEvidence(wssHostEmptyRuleset)
	for _, tc := range []struct {
		name   string
		change func(*WSSWGFirewallEvidence)
	}{
		{"legacy-frontend-v4", func(e *WSSWGFirewallEvidence) { e.IPTablesV4 = "iptables v1.8.11 (legacy)" }},
		{"legacy-frontend-v6", func(e *WSSWGFirewallEvidence) { e.IPTablesV6 = "ip6tables v1.8.11 (legacy)" }},
		{"unknown-frontend", func(e *WSSWGFirewallEvidence) { e.IPTablesV4 = "" }},
		{"no-legacy-v4-readback", func(e *WSSWGFirewallEvidence) { e.LegacySaveV4 = nil }},
		{"no-legacy-v6-readback", func(e *WSSWGFirewallEvidence) { e.LegacySaveV6 = nil }},
		{"legacy-input-accept-rule", func(e *WSSWGFirewallEvidence) {
			e.LegacySaveV4 = []byte(strings.Replace(wssHostLegacyEmpty, "COMMIT", "-A INPUT -p udp --dport 51820 -j ACCEPT\nCOMMIT", 1))
		}},
		{"legacy-custom-chain", func(e *WSSWGFirewallEvidence) { e.LegacySaveV4 = []byte("*filter\n:FOREIGN - [0:0]\nCOMMIT\n") }},
		{"legacy-drop-policy", func(e *WSSWGFirewallEvidence) { e.LegacySaveV6 = []byte("*filter\n:INPUT DROP [0:0]\nCOMMIT\n") }},
		{"truncated-legacy", func(e *WSSWGFirewallEvidence) { e.LegacySaveV4 = []byte("*filter\n:INPUT ACCEPT [0:0]\n") }},
		{"malformed-legacy", func(e *WSSWGFirewallEvidence) { e.LegacySaveV4 = []byte("*filter\n:INPUT ACCEPT [oops]\nCOMMIT\n") }},
	} {
		t.Run(tc.name, func(t *testing.T) {
			e := legible
			tc.change(&e)
			if err := p.CheckWSSWGFirewallCoexistence(e); err == nil {
				t.Fatal("unverified IPv4/IPv6 legacy coexistence accepted")
			}
		})
	}
}

type wssHostReadbackRunner struct {
	calls   []string
	fail    string
	failErr error
	stderr  string
}

func (r *wssHostReadbackRunner) Run(_ context.Context, _ string, _ ...string) (CommandResult, error) {
	return CommandResult{}, fmt.Errorf("unbounded execution forbidden")
}

func (r *wssHostReadbackRunner) RunBounded(_ context.Context, limits CaptureLimits, name string, args ...string) (CommandResult, error) {
	command := strings.Join(append([]string{name}, args...), " ")
	r.calls = append(r.calls, command)
	if limits.Stdout <= 0 || limits.Stderr <= 0 || limits.Stdout > 8<<20 {
		return CommandResult{}, fmt.Errorf("unsafe readback ceiling")
	}
	if command == r.fail {
		if r.failErr != nil {
			return CommandResult{}, r.failErr
		}
		return CommandResult{}, fmt.Errorf("permission denied")
	}
	if r.stderr != "" {
		return CommandResult{Stderr: []byte(r.stderr)}, nil
	}
	switch command {
	case "nft -j list ruleset":
		return CommandResult{Stdout: []byte(wssHostEmptyRuleset)}, nil
	case "iptables -V":
		return CommandResult{Stdout: []byte("iptables v1.8.11 (nf_tables)\n")}, nil
	case "ip6tables -V":
		return CommandResult{Stdout: []byte("ip6tables v1.8.11 (nf_tables)\n")}, nil
	case "iptables-legacy-save":
		return CommandResult{Stdout: []byte(wssHostLegacyEmpty)}, nil
	case "ip6tables-legacy-save":
		return CommandResult{Stdout: nil}, nil // successful but empty
	default:
		return CommandResult{}, fmt.Errorf("unexpected probe command")
	}
}

func TestWSSWGHostProbeUsesOnlyBoundedReadOnlyCommands(t *testing.T) {
	p := wssGuardFixture(t)
	r := &wssHostReadbackRunner{}
	if err := p.ProbeWSSWGFirewallCoexistence(context.Background(), r); err != nil {
		t.Fatalf("complete passive host evidence not accepted: %v", err)
	}
	want := []string{
		"nft -j list ruleset", "iptables -V", "ip6tables -V",
		"iptables-legacy-save", "ip6tables-legacy-save",
	}
	if !reflect.DeepEqual(r.calls, want) {
		t.Fatalf("unexpected firewall commands: %q", r.calls)
	}
	r = &wssHostReadbackRunner{fail: "ip6tables-legacy-save"}
	if err := p.ProbeWSSWGFirewallCoexistence(context.Background(), r); err == nil || !strings.Contains(err.Error(), "IPv6 legacy") {
		t.Fatalf("missing mandatory IPv6 legacy evidence not rejected: %v", err)
	}
	if err := p.ProbeWSSWGFirewallCoexistence(context.Background(), nil); err == nil {
		t.Fatal("nil bounded runner admitted")
	}
}

func TestWSSWGHostProbeErrorsNeverForwardRunnerDiagnostics(t *testing.T) {
	p := wssGuardFixture(t)
	const secret = "SENSITIVE_FOREIGN_FIREWALL_DIAGNOSTIC_TOKEN"
	sentinel := errors.New("runner-" + secret)
	tests := []struct {
		name        string
		input       error
		is          error
		wantExit    int
		wantTimeout bool
		wantCancel  bool
	}{
		{"arbitrary-error", fmt.Errorf("private stderr %s: %w", secret, sentinel), nil, 0, false, false},
		{"output-limit", fmt.Errorf("%s: %w", secret, ErrOutputLimit), ErrOutputLimit, 0, false, false},
		{"deadline-exceeded", fmt.Errorf("%s: %w", secret, context.DeadlineExceeded), context.DeadlineExceeded, 0, false, false},
		{"canceled", fmt.Errorf("%s: %w", secret, context.Canceled), context.Canceled, 0, false, false},
		{"typed-command-error", &CommandError{Command: secret, ExitCode: 37, cause: sentinel}, nil, 37, false, false},
		{"typed-wrapped-command-error", fmt.Errorf("%s: %w", secret, &CommandError{Command: secret, ExitCode: 53, cause: sentinel}), nil, 53, false, false},
		{"typed-command-timeout", &CommandError{Command: secret, ExitCode: -1, TimedOut: true, cause: sentinel}, nil, 0, true, false},
		{"typed-command-canceled", &CommandError{Command: secret, ExitCode: -1, Canceled: true, cause: sentinel}, nil, 0, false, true},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			r := &wssHostReadbackRunner{fail: "nft -j list ruleset", failErr: tt.input}
			err := p.ProbeWSSWGFirewallCoexistence(context.Background(), r)
			if err == nil {
				t.Fatal("untrusted runner error was admitted")
			}
			if strings.Contains(err.Error(), secret) || strings.Contains(fmt.Sprintf("%+v", err), secret) ||
				errors.Is(err, sentinel) {
				t.Fatalf("untrusted runner diagnostic leaked via returned error: %v", err)
			}
			if !strings.Contains(err.Error(), "WSS WG nft readback") {
				t.Fatalf("fixed diagnostic stage lost: %v", err)
			}
			if tt.is != nil && !errors.Is(err, tt.is) {
				t.Fatalf("safe typed sentinel %v was lost: %v", tt.is, err)
			}
			if tt.wantExit != 0 || tt.wantTimeout || tt.wantCancel {
				var safe *CommandError
				if !errors.As(err, &safe) || (tt.wantExit != 0 && safe.ExitCode != tt.wantExit) ||
					safe.Command != "nft" || safe.Unwrap() != nil ||
					safe.TimedOut != tt.wantTimeout || safe.Canceled != tt.wantCancel {
					t.Fatalf("safe numeric exit information was lost or polluted: %v", err)
				}
			}
		})
	}
	// Even a successful runner may return warning/error output carrying
	// sensitive firewall metadata. The stage-only error must not leak it.
	r := &wssHostReadbackRunner{stderr: secret}
	err := p.ProbeWSSWGFirewallCoexistence(context.Background(), r)
	if err == nil || strings.Contains(err.Error(), secret) {
		t.Fatalf("runner stderr was exposed: %v", err)
	}
}

func TestWSSWGHostCoexistenceIsolatedNftReadback(t *testing.T) {
	path := os.Getenv("STL_WSS_HOST_NFT_JSON")
	if path == "" {
		t.Skip("disposable namespace nft ruleset snapshot not supplied")
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	p := wssGuardFixture(t)
	err = p.CheckWSSWGNFTCoexistence(data)
	if os.Getenv("STL_WSS_HOST_EXPECT_REJECT") == "yes" {
		if err == nil {
			t.Fatal("foreign pre-guard hook unexpectedly admitted")
		}
	} else if err != nil {
		t.Fatalf("expected read-only nft compatibility observation rejected: %v", err)
	}
}
