const fixtureID = domain.LinkID("lnk_0123456789abcdef0123456789abcdef")
const fixtureNonce = "0123456789abcdef0123456789abcdef"
const emptyRuleset = `{"nftables":[{"metainfo":{"version":"1.1.3","json_schema_version":1}}]}`

type guardTestRunner struct {
	calls                                       []string
	table                                       string
	exact                                       []byte
	nftRules                                    []byte
	present                                     bool
	drift                                       bool
	badTables                                   bool
	failed                                      string
	stderrFor                                   string
	wgNames, wgPublic, wgPorts, ssListen, ssAll string
	cancelReadback                              context.CancelFunc
}

func (r *guardTestRunner) Run(ctx context.Context, name string, args ...string) (linux.CommandResult, error) {
	return r.RunBounded(ctx, linux.CaptureLimits{Stdout: 8 << 20, Stderr: 64 << 10}, name, args...)
}

func (r *guardTestRunner) RunBounded(ctx context.Context, _ linux.CaptureLimits, name string, args ...string) (linux.CommandResult, error) {
	command := strings.TrimSpace(name + " " + strings.Join(args, " "))
	r.calls = append(r.calls, command)
	if command == r.failed {
		return linux.CommandResult{}, errors.New("SENSITIVE_FOREIGN_RESULT")
	}
	out := linux.CommandResult{}
	switch command {
	case "nft -j list ruleset":
		out.Stdout = r.nftRules
	case "iptables -V":
		out.Stdout = []byte("iptables v1.8.11 (nf_tables)\n")
	case "ip6tables -V":
		out.Stdout = []byte("ip6tables v1.8.11 (nf_tables)\n")
	case "iptables-legacy-save":
		out.Stdout = []byte("# Generated by iptables-save v1.8.11\n*filter\n:INPUT ACCEPT [0:0]\n:FORWARD ACCEPT [0:0]\n:OUTPUT ACCEPT [0:0]\nCOMMIT\n# Completed\n")
	case "ip6tables-legacy-save":
		out.Stdout = []byte{}
	case "nft -j list tables":
		if r.badTables {
			out.Stdout = []byte(`{"nftables":[]}`)
		} else if r.present {
			out.Stdout = []byte(fmt.Sprintf(`{"nftables":[{"metainfo":{"version":"1.1.3","json_schema_version":1}},{"table":{"family":"inet","name":%q,"handle":2}}]}`, r.table))
		} else {
			out.Stdout = []byte(emptyRuleset)
		}
	case "nft -j list table inet " + r.table:
		if r.cancelReadback != nil {
			r.cancelReadback()
		}
		out.Stdout = r.exact
		if r.drift {
			out.Stdout = []byte(strings.Replace(string(r.exact), fixtureNonce, "ffffffffffffffffffffffffffffffff", 1))
		}
	case "wg show interfaces":
		out.Stdout = []byte(r.wgNames)
	case "wg show all public-key":
		out.Stdout = []byte(r.wgPublic)
	case "wg show all listen-port":
		out.Stdout = []byte(r.wgPorts)
	case "ss -H -u -l -n":
		out.Stdout = []byte(r.ssListen)
	case "ss -H -u -a -n":
		out.Stdout = []byte(r.ssAll)
	default:
		return linux.CommandResult{}, fmt.Errorf("unplanned fake host observation")
	}
	if command == r.stderrFor {
		out.Stderr = []byte("SENSITIVE_FOREIGN_STDERR")
	}
	return out, nil
}

func testWG() domain.WireGuardOptions {
	return domain.WireGuardOptions{
		LocalPublicKey: base64.StdEncoding.EncodeToString([]byte(strings.Repeat("a", 32))),
		PeerPublicKey:  base64.StdEncoding.EncodeToString([]byte(strings.Repeat("b", 32))),
		ListenPort:     51820, PeerPort: 51821,
	}
}

func guardFixture(t *testing.T) (*guardTestRunner, domain.WireGuardOptions) {
	t.Helper()
	wg := testWG()
	plan, err := linux.NewQUICWGIngressPlan(fixtureID, wg.ListenPort, fixtureNonce)
	if err != nil {
		t.Fatal(err)
	}
	batch, err := plan.NFTBatch()
	if err != nil {
		t.Fatal(err)
	}
	part := strings.Split(strings.Split(batch, " comment \"")[1], "\"")[0]
	table := plan.TableName()
	exact := []byte(fmt.Sprintf(`{"nftables":[
{"metainfo":{"version":"1.1.3","json_schema_version":1}},
{"table":{"family":"inet","name":%q,"handle":1}},
{"chain":{"family":"inet","table":%q,"name":"ingress","handle":1,"type":"filter","hook":"input","prio":-250,"policy":"accept"}},
{"rule":{"family":"inet","table":%q,"chain":"ingress","handle":2,"comment":%q,"expr":[
{"match":{"op":"!=","left":{"meta":{"key":"iifname"}},"right":"lo"}},
{"match":{"op":"==","left":{"payload":{"protocol":"udp","field":"dport"}},"right":%d}},
{"counter":{"packets":0,"bytes":0}},{"drop":null}]}}
]}`, table, table, table, part, wg.ListenPort))
	if err := plan.VerifyNFTJSON(exact); err != nil {
		t.Fatalf("nft snapshot test fixture is foreign: %v", err)
	}
	return &guardTestRunner{table: table, exact: exact, nftRules: []byte(emptyRuleset)}, wg
}

// threadWitnessReader verifies that every host preflight/readback query
// executes on the same OS thread that dispatches the original nft CREATE.
type threadWitnessReader struct {
	*guardTestRunner
	originTID int
	migrated  bool
}

func (r *threadWitnessReader) RunBounded(ctx context.Context, lim linux.CaptureLimits, name string, args ...string) (linux.CommandResult, error) {
	current := unix.Gettid()
	if r.originTID == 0 {
		r.originTID = current
	} else if current != r.originTID {
		r.migrated = true
	}
	return r.guardTestRunner.RunBounded(ctx, lim, name, args...)
}

func TestOriginalGuardPinsPreflightCreateAndReadbackToOneOSThread(t *testing.T) {
	fixture, wg := guardFixture(t)
	runner := &threadWitnessReader{guardTestRunner: fixture}
	applied := 0
	err := publishOriginal(context.Background(), runner, fixtureID, fixtureNonce, wg,
		func(context.Context, string) error {
			applied++
			if runner.originTID == 0 || unix.Gettid() != runner.originTID {
				t.Fatal("nft CREATE migrated away from preflight network namespace thread")
			}
			// Under goroutine rescheduling, the publisher must remain bound
			// to the same OS thread until strict post-effect readback.
			runtime.Gosched()
			fixture.present = true
			return nil
		})
	if err != nil || applied != 1 || runner.migrated {
		t.Fatalf("original QUIC ingress OS-thread affinity lost: %v dispatches=%d migrated=%t",
			err, applied, runner.migrated)
	}
}

func TestOriginalGuardNamespaceDriftIsNeverAnEffectOrOwnershipPermit(t *testing.T) {
	// These inputs simulate readback drift; the real production namespace
	// reader is fixed by publishOriginal. No test changes an OS namespace.
	for _, tc := range []struct {
		name         string
		driftAt      int
		dispatches   int
		uncertain    bool
		readbackDone bool
		wantReads    int
	}{
		{"before dispatch", 2, 0, false, false, 2},
		{"after dispatch before readback", 3, 1, true, false, 3},
		{"after strict readback", 4, 1, true, true, 4},
		{"stable namespace", 0, 1, false, true, 4},
	} {
		t.Run(tc.name, func(t *testing.T) {
			runner, wg := guardFixture(t)
			reads := 0
			readNS := func() (string, error) {
				reads++
				if reads == tc.driftAt {
					return "net:[4026532999]", nil
				}
				return "net:[4026532789]", nil
			}
			dispatched := 0
			err := publishOriginalWithNetworkNS(context.Background(), runner, fixtureID, fixtureNonce, wg,
				func(_ context.Context, batch string) error {
					dispatched++
					if !strings.HasPrefix(batch, "create table inet "+runner.table) {
						t.Fatal("unexpected nft CREATE identity")
					}
					runner.present = true // test-owned, not deleted or adopted
					return nil
				}, readNS)
			if dispatched != tc.dispatches || reads != tc.wantReads ||
				runner.present != (tc.dispatches == 1) {
				t.Fatalf("namespace drift host effect mismatch: dispatched=%d reads=%d present=%t err=%v",
					dispatched, reads, runner.present, err)
			}
			if tc.driftAt == 0 {
				if err != nil {
					t.Fatalf("stable namespace rejected: %v", err)
				}
			} else if err == nil || errors.Is(err, errEffectUncertain) != tc.uncertain {
				t.Fatalf("namespace drift incorrectly authorized effect/cleanup: %v", err)
			}
			strictReadback := false
			for _, call := range runner.calls {
				if call == "nft -j list table inet "+runner.table {
					strictReadback = true
				}
				if strings.Contains(call, "delete") || strings.Contains(call, "flush") {
					t.Fatalf("namespace drift triggered destructive host command: %q", call)
				}
			}
			if strictReadback != tc.readbackDone {
				t.Fatalf("unexpected post-effect readback: got %t want %t", strictReadback, tc.readbackDone)
			}
		})
	}
}

func TestOriginalGuardStrictCreateAndOneTimeReadback(t *testing.T) {
	runner, wg := guardFixture(t)
	applied := 0
	err := publishOriginal(context.Background(), runner, fixtureID, fixtureNonce, wg, func(ctx context.Context, batch string) error {
		applied++
		if ctx.Err() != nil || runner.present || !strings.HasPrefix(batch, "create table inet "+runner.table+"\n") ||
			!strings.Contains(batch, fixtureNonce) || !strings.Contains(batch, "counter drop") ||
			strings.Contains(batch, "flush") || strings.Contains(batch, "delete") {
			t.Fatal("foreign or destructive nft transaction")
		}
		runner.present = true
		return nil
	})
	if err != nil || applied != 1 {
		t.Fatalf("guard did not create the exact original: %v, calls %d", err, applied)
	}
	expected := []string{"nft -j list ruleset", "iptables -V", "ip6tables -V", "iptables-legacy-save", "ip6tables-legacy-save",
		"nft -j list tables", "wg show interfaces", "wg show all public-key", "wg show all listen-port",
		"ss -H -u -l -n", "ss -H -u -a -n", "nft -j list tables", "nft -j list table inet " + runner.table}
	if !reflect.DeepEqual(expected, runner.calls) {
		t.Fatalf("host readback order/coverage differs: %q", runner.calls)
	}
	if err := publishOriginal(context.Background(), runner, fixtureID, fixtureNonce, wg, func(context.Context, string) error {
		t.Fatal("same-name existing guard was overwritten/adopted")
		return nil
	}); err == nil {
		t.Fatal("existing same-byte guard was adopted")
	}
}

func TestOriginalGuardRejectsHostConflictsAndDiagnosticsBeforeDispatch(t *testing.T) {
	for _, tt := range []struct {
		name      string
		change    func(*guardTestRunner, domain.WireGuardOptions)
		post      bool
		uncertain bool
	}{
		{"preexisting identical guard", func(r *guardTestRunner, _ domain.WireGuardOptions) { r.present = true }, false, false},
		{"foreign early nft hook", func(r *guardTestRunner, _ domain.WireGuardOptions) {
			r.nftRules = []byte(`{"nftables":[{"metainfo":{"version":"1.1.3","json_schema_version":1}},{"table":{"family":"inet","name":"foreign"}},{"chain":{"family":"inet","table":"foreign","name":"INPUT","type":"filter","hook":"input","prio":-300,"policy":"accept"}},{"rule":{"family":"inet","table":"foreign","chain":"INPUT","expr":[{"accept":null}]}}]}`)
		}, false, false},
		{"invalid nft inventory", func(r *guardTestRunner, _ domain.WireGuardOptions) { r.badTables = true }, false, false},
		{"occupied WG key", func(r *guardTestRunner, w domain.WireGuardOptions) {
			r.wgNames = "foreign0"
			r.wgPublic = "foreign0 " + w.LocalPublicKey + "\n"
			r.wgPorts = "foreign0 51822\n"
		}, false, false},
		{"occupied WG UDP port", func(r *guardTestRunner, _ domain.WireGuardOptions) {
			r.wgNames = "foreign0"
			r.wgPublic = "foreign0 " + base64.StdEncoding.EncodeToString([]byte(strings.Repeat("c", 32))) + "\n"
			r.wgPorts = "foreign0 51820\n"
		}, false, false},
		{"migrated WG socket", func(r *guardTestRunner, _ domain.WireGuardOptions) {
			r.ssListen = "UNCONN 0 0 0.0.0.0:51820 0.0.0.0:*\n"
		}, false, false},
		{"connected UDP socket", func(r *guardTestRunner, _ domain.WireGuardOptions) {
			r.ssAll = "ESTAB 0 0 127.0.0.1:51820 127.0.0.1:8899\n"
		}, false, false},
		{"malformed socket", func(r *guardTestRunner, _ domain.WireGuardOptions) { r.ssAll = "INCOMPLETE\n" }, false, false},
		{"missing wg inventory", func(r *guardTestRunner, _ domain.WireGuardOptions) { r.failed = "wg show interfaces" }, false, false},
		{"post-create altered marker", func(r *guardTestRunner, _ domain.WireGuardOptions) { r.drift = true }, true, true},
	} {
		t.Run(tt.name, func(t *testing.T) {
			runner, wg := guardFixture(t)
			tt.change(runner, wg)
			applied := 0
			err := publishOriginal(context.Background(), runner, fixtureID, fixtureNonce, wg, func(context.Context, string) error { applied++; runner.present = true; return nil })
			want := 0
			if tt.post {
				want = 1
			}
			if err == nil || applied != want || errors.Is(err, errEffectUncertain) != tt.uncertain {
				t.Fatalf("unsafe host admitted: %v attempts=%d", err, applied)
			}
			if strings.Contains(err.Error(), "SENSITIVE_FOREIGN") {
				t.Fatal("untrusted host diagnostics leaked")
			}
		})
	}
}

