func TestOriginalGuardPreservesAmbiguousDispatchAndCancellation(t *testing.T) {
	runner, wg := guardFixture(t)
	err := publishOriginal(context.Background(), runner, fixtureID, fixtureNonce, wg, func(context.Context, string) error {
		runner.present = true
		return errors.New("SENSITIVE_FOREIGN_NFT_ERROR")
	})
	if !errors.Is(err, errEffectUncertain) || strings.Contains(err.Error(), "SENSITIVE_FOREIGN") || !runner.present {
		t.Fatalf("dispatched failed nft improperly discarded: %v", err)
	}
	ctx, cancel := context.WithCancel(context.Background())
	runner, wg = guardFixture(t)
	runner.cancelReadback = cancel
	err = publishOriginal(ctx, runner, fixtureID, fixtureNonce, wg, func(context.Context, string) error { runner.present = true; return nil })
	if !errors.Is(err, errEffectUncertain) {
		t.Fatalf("canceled post-create nft falsely accepted: %v", err)
	}
	runner, wg = guardFixture(t)
	ctx, cancel = context.WithCancel(context.Background())
	cancel()
	if err := publishOriginal(ctx, runner, fixtureID, fixtureNonce, wg, func(context.Context, string) error { t.Fatal("canceled nft mutation"); return nil }); err == nil || len(runner.calls) > 0 {
		t.Fatal("canceled operation reached host")
	}
}

